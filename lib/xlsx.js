// Minimal dependency-free .xlsx writer (multiple sheets, bold header row,
// column widths, frozen header). Produces a standard ZIP (deflate) container.
const zlib = require('zlib');

function esc(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/[\x00-\x08\x0B\x0C\x0E-\x1F]/g, '');
}

function colName(i) {
  let s = '';
  i += 1;
  while (i > 0) {
    const m = (i - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    i = Math.floor((i - 1) / 26);
  }
  return s;
}

// styles: 0 default, 1 header, 2 green "P", 3 red "A", 4 title
function sheetXml(sheet) {
  const { rows, widths = [], styles = {} } = sheet;
  const cols = widths.length
    ? '<cols>' + widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('') + '</cols>'
    : '';
  const body = rows
    .map((row, r) => {
      const cells = row
        .map((v, c) => {
          if (v === null || v === undefined || v === '') return '';
          const ref = colName(c) + (r + 1);
          let s = r === (sheet.headerRow ?? 0) ? 1 : 0;
          if (styles[`${r},${c}`] !== undefined) s = styles[`${r},${c}`];
          else if (r > (sheet.headerRow ?? 0) && sheet.markPA) {
            if (v === 'P') s = 2;
            else if (v === 'A') s = 3;
          }
          const sa = s ? ` s="${s}"` : '';
          if (typeof v === 'number' && isFinite(v)) return `<c r="${ref}"${sa}><v>${v}</v></c>`;
          return `<c r="${ref}"${sa} t="inlineStr"><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
        })
        .join('');
      return `<row r="${r + 1}">${cells}</row>`;
    })
    .join('');
  const hr = (sheet.headerRow ?? 0) + 1;
  const pane = `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${hr}" topLeftCell="A${hr + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>`;
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}${cols}<sheetData>${body}</sheetData></worksheet>`;
}

